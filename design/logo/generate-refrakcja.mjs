// Generates the "Refrakcja" logo: src/lib/brand/logo.ts (outlined paths for <BrandLogo>) and
// design/logo/final-refrakcja/*.svg (lockups, signet, favicon, app icon).
// Run from this folder:
//   npm i --no-save opentype.js@1.3.4 paper@0.12.18 @fontsource/sora && node generate-refrakcja.mjs
import fs from "node:fs";
import opentype from "opentype.js";
import paper from "paper";

paper.setup(new paper.Size(10, 10));
const ROOT = new URL("../..", import.meta.url).pathname;
const FONTS = process.env.FONTS_DIR ?? "node_modules/@fontsource/sora/files";
const font = (w) => {
  const b = fs.readFileSync(`${FONTS}/sora-latin-${w}-normal.woff`);
  return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
};
const S800 = font(800);
const S500 = font(500);

// Two waterlines (fractions of x-height): the first sits just under the "e" crossbar (Sora: 22.6–32.4 % of size).
// Each layer below a line shifts further right, like looking deeper into water.
const P = { size: 100, track: -0.008, rtExtra: 0.02, lines: [0.385, 0.12], gap: 0.02, shifts: [0.03, 0.06], studio: 0.45, studioGap: 0.1 };
const round = (d) => d.replace(/-?\d+\.\d+/g, (m) => String(+(+m).toFixed(2)));

function wordPath(f, text, size, track, extra = {}) {
  let pen = 0;
  const glyphs = f.stringToGlyphs(text);
  const parts = [];
  glyphs.forEach((g, i) => {
    parts.push(g.getPath(pen, 0, size).toPathData(3));
    pen += (g.advanceWidth * size) / f.unitsPerEm + track * size;
    if (i < glyphs.length - 1) {
      pen += (f.getKerningValue(g, glyphs[i + 1]) * size) / f.unitsPerEm + (extra[text[i] + text[i + 1]] ?? 0) * size;
    }
  });
  return { cp: new paper.CompoundPath(parts.join("")), width: pen - track * size };
}

function refract(cp, size) {
  const xh = (S800.tables.os2.sxHeight / 1000) * size;
  const g = (P.gap * size) / 2;
  const big = 1e4;
  const band = (y0, y1) => cp.intersect(new paper.Path.Rectangle(new paper.Rectangle(-big, y0, 3 * big, y1 - y0)), { insert: false });
  const [l1, l2] = P.lines.map((f) => -xh * f);
  const top = band(-big, l1 - g);
  const mid = band(l1 + g, l2 - g).translate(new paper.Point(P.shifts[0] * size, 0));
  const deep = band(l2 + g, big).translate(new paper.Point(P.shifts[1] * size, 0));
  return { top, mid, deep };
}

// lockup
const word = wordPath(S800, "blueport", P.size, P.track, { rt: P.rtExtra });
const { top, mid, deep } = refract(word.cp, P.size);
const studio = wordPath(S500, "studio", P.size * P.studio, 0.01);
studio.cp.translate(new paper.Point(word.width + P.shifts[1] * P.size + P.studioGap * P.size, 0));
const parts = [top, mid, deep, studio.cp];
const box = new paper.Group(parts.map((p) => p.clone({ insert: false }))).bounds;
for (const p of parts) p.translate(new paper.Point(-box.x, -box.y));
const LW = +box.width.toFixed(2);
const LH = +box.height.toFixed(2);
const L = { top: round(top.pathData), mid: round(mid.pathData), deep: round(deep.pathData), studio: round(studio.cp.pathData) };

// signet: the refracted "b", centred in a square
const b = wordPath(S800, "b", P.size, 0);
const sb = refract(b.cp, P.size);
const sparts = [sb.top, sb.mid, sb.deep];
const bb = new paper.Group(sparts.map((p) => p.clone({ insert: false }))).bounds;
const SS = +Math.max(bb.width, bb.height).toFixed(2);
const so = new paper.Point(-bb.x + (SS - bb.width) / 2, -bb.y + (SS - bb.height) / 2);
for (const p of sparts) p.translate(so);
const G = { top: round(sb.top.pathData), mid: round(sb.mid.pathData), deep: round(sb.deep.pathData) };

fs.mkdirSync(`${ROOT}/src/lib/brand`, { recursive: true });
fs.writeFileSync(
  `${ROOT}/src/lib/brand/logo.ts`,
  `/**
 * "Refrakcja" lockup: "blueport" in Sora ExtraBold cut by two waterlines; each layer below shifts further right,
 * like looking deeper into water. "studio" is Sora Medium. Outlines from Sora (SIL OFL), generated by
 * design/logo/generate-refrakcja.mjs: regenerate, do not hand-edit.
 */
export const LOGO_VIEWBOX = "0 0 ${LW} ${LH}";
export const LOGO_RATIO = ${+(LW / LH).toFixed(4)};
export const LOGO_ABOVE =
  "${L.top}";
export const LOGO_SHALLOW =
  "${L.mid}";
export const LOGO_DEEP =
  "${L.deep}";
export const LOGO_STUDIO =
  "${L.studio}";

/** Signet: the same cut applied to a lone "b", centred in a square. */
export const SIGNET_VIEWBOX = "0 0 ${SS} ${SS}";
export const SIGNET_ABOVE =
  "${G.top}";
export const SIGNET_SHALLOW =
  "${G.mid}";
export const SIGNET_DEEP =
  "${G.deep}";
`,
);

const NAVY = "#08192A", BLUE = "#3D8EFF", DEEP = "#2563C9", INK = "#F3F6F9", SUB = "#A9BDCC", SUB_LIGHT = "#4A6275";
const out = `${ROOT}/design/logo/final-refrakcja`;
fs.mkdirSync(out, { recursive: true });
const lockup = (ink, blue, deep, sub, bg) => {
  const vb = bg ? `-12 -12 ${LW + 24} ${LH + 24}` : `0 0 ${LW} ${LH}`;
  const fill = bg ? `<rect x="-12" y="-12" width="${LW + 24}" height="${LH + 24}" fill="${bg}"/>` : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}"><title>blueport studio</title>${fill}<path fill="${ink}" d="${L.top}"/><path fill="${blue}" d="${L.mid}"/><path fill="${deep}" d="${L.deep}"/><path fill="${sub}" d="${L.studio}"/></svg>`;
};
fs.writeFileSync(`${out}/lockup-on-dark.svg`, lockup(INK, BLUE, DEEP, SUB));
fs.writeFileSync(`${out}/lockup-on-dark-bg.svg`, lockup(INK, BLUE, DEEP, SUB, NAVY));
fs.writeFileSync(`${out}/lockup-on-light.svg`, lockup(NAVY, BLUE, DEEP, SUB_LIGHT));
fs.writeFileSync(`${out}/lockup-black.svg`, lockup("#000", "#000", "#000", "#000"));
fs.writeFileSync(`${out}/lockup-white.svg`, lockup("#fff", "#fff", "#fff", "#fff"));
const tile = (pad, radius) => {
  const t = +(SS * (1 + 2 * pad)).toFixed(2);
  const o = +(SS * pad).toFixed(2);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${t} ${t}"><title>blueport studio</title><rect width="${t}" height="${t}" rx="${+(t * radius).toFixed(2)}" fill="${NAVY}"/><g transform="translate(${o} ${o})"><path fill="${INK}" d="${G.top}"/><path fill="${BLUE}" d="${G.mid}"/><path fill="${DEEP}" d="${G.deep}"/></g></svg>`;
};
fs.writeFileSync(`${out}/signet-tile.svg`, tile(0.22, 0.22));
fs.writeFileSync(`${out}/favicon.svg`, tile(0.12, 0.2));
fs.writeFileSync(`${out}/apple-icon.svg`, tile(0.28, 0));
fs.writeFileSync(
  `${out}/signet-black.svg`,
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SS} ${SS}"><title>blueport studio</title><path d="${G.top}"/><path d="${G.mid}"/><path d="${G.deep}"/></svg>`,
);
console.log(`lockup ${LW}×${LH}, signet ${SS}`);
