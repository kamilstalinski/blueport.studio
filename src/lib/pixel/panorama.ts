/** Runs of one tone: "X" lit, "o" shadow. */
export function panoramaRuns(tone: "X" | "o"): CraneRun[] {
  const pattern = new RegExp(`${tone}+`, "g");
  return PANORAMA_ROWS.flatMap((row, y) => [...row.matchAll(pattern)].map((match) => ({ x: match.index, y, w: match[0].length })));
}

